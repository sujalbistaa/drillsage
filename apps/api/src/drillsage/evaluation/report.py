"""Gold-set extraction report (`eval/reports/extraction_gold.{md,json}`). Never hand-edited."""

import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from drillsage.domain.hazards import HazardType, is_geological
from drillsage.evaluation.gold import (
    SAMPLE_VERSION,
    GoldItem,
    Label,
    Line,
    Predictor,
    coverage,
    micro,
    score,
)
from drillsage.extract.rules import HitSource, classify_activity


def rule_depth(line: Line, hazard: str) -> float | None:
    """The depth the rule tier would give this line's problem (as the event logic does)."""
    hits = classify_activity(line.code, line.state_detail, line.text)
    stated = [
        d
        for h in hits
        if h.hazard.value == hazard and h.source is HitSource.TEXT
        for d in h.depths_m
    ]
    if stated:
        return max(stated)
    return line.md_m if line.md_m else None


def build(
    items: Sequence[GoldItem], labels: Mapping[str, Label], predictors: Mapping[str, Predictor]
) -> dict[str, Any]:
    tiers: dict[str, Any] = {}
    for name, predictor in predictors.items():
        scores = score(items, labels, predictor, depth_of=rule_depth)
        tiers[name] = {
            "micro": micro(scores).summary(),
            "geological_micro": micro(
                {h: s for h, s in scores.items() if is_geological(HazardType(h))}
            ).summary(),
            "by_hazard": {h: scores[h].summary() for h in sorted(scores)},
        }
    return {"sample_version": SAMPLE_VERSION, "coverage": coverage(items, labels), "tiers": tiers}


def _cell(value: object) -> str:
    return "-" if value is None else str(value)


def write(payload: dict[str, Any], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "extraction_gold.json").write_text(
        json.dumps(payload, indent=2) + "\n", encoding="utf-8"
    )
    cov = payload["coverage"]
    summary_rows = "\n".join(
        f"| {name} | {_cell(t['micro']['precision'])} | {_cell(t['micro']['recall'])} "
        f"| {_cell(t['micro']['f1'])} | {_cell(t['geological_micro']['f1'])} "
        f"| {_cell(t['micro']['median_depth_error_m'])} |"
        for name, t in payload["tiers"].items()
    )
    sections = []
    for name, tier in payload["tiers"].items():
        rows = "\n".join(
            f"| {h} | {_cell(s['precision'])} | {_cell(s['recall'])} | {_cell(s['f1'])} "
            f"| {s['tp']} | {s['fp']} | {s['fn']} | {_cell(s['median_depth_error_m'])} |"
            for h, s in tier["by_hazard"].items()
        )
        sections.append(
            f"### {name}\n\n| Hazard | Precision | Recall | F1 | TP | FP | FN "
            f"| Median depth error (m) |\n|---|---:|---:|---:|---:|---:|---:|---:|\n{rows}\n"
        )
    by_stratum = ", ".join(f"{k} {v}" for k, v in sorted(cov["by_stratum"].items()))
    md = f"""# Event extraction accuracy (gold set)

Generated by `make gold-eval` (`drillsage-data gold-eval`). Do not edit by hand.
Sample `{payload["sample_version"]}`: {cov["labelled"]} of {cov["items"]} activities
labelled by hand ({cov["unsure"]} marked unsure and excluded; {cov["with_hazard"]} contain a
problem).
Labelled per stratum: {by_stratum}.

| Tier | Precision | Recall | F1 | F1, geological hazards | Median depth error (m) |
|---|---:|---:|---:|---:|---:|
{summary_rows}

**How to read this.** Scores are per activity line: does the tier assign the hazard the human
labeller assigned? The sample is stratified (20 lines per hazard the rules flag, 120 lines
the rules do not flag). Every count is weighted by the inverse of its sampling rate, so
precision and recall estimate the whole corpus of 16,456 lines, not the sample. TP, FP and FN
are the raw, unweighted numbers of lines. Recall rests mostly on the unflagged stratum, where
each line stands for about 110 others, so it has the widest uncertainty.

Tiers: *codes* is the operator's activity codes alone, *lexicon* the phrase rules alone,
*rules* both. The LLM tier appears here once it has read the reports in the sample.

## Per hazard

{"".join(sections)}"""
    (out_dir / "extraction_gold.md").write_text(md, encoding="utf-8")
